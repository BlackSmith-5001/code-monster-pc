export function getBugInfo(bugType) {
  return BUG_LIBRARY[bugType] || BUG_LIBRARY.zenkaku_equal;
}

export function getBugBookEntries() {
  return Object.entries(BUG_LIBRARY).map(([bugType, info], index) => ({
    bugType,
    no: info?.no || String(index + 1).padStart(3, "0"),
    name: info?.name || bugType,
    icon: info?.icon || "🐞",
    color: info?.color || "#94a3b8",
    symptom: info?.symptom || "症状データを準備中です。",
    fix: info?.fix || "倒し方データを準備中です。",
    beginnerTip: info?.beginnerTip || "初心者向けメモを準備中です。",
    masterComment: info?.masterComment || "師匠コメントを準備中です。",
    stages: info?.stages || "全レベル",
    ...info,
  }));
}
